// Generates src/shared/icons.ts from lucide-static (ISC). Run: node scripts/make-icons.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const NAMES = [
  'banknote',
  'calendar-clock',
  'percent',
  'list-checks',
  'circle-slash',
  'repeat',
  'copy',
  'rotate-ccw',
  'share-2',
  'download',
  'check',
  'triangle-alert',
  'info',
  'x',
  'clipboard-paste',
  'scan-search',
  'external-link',
  'wifi-off',
  'shield-check',
  'chevron-down',
  'trash-2',
  'arrow-down',
  'corner-left-up',
  'file-text',
];

const body = (svg) =>
  svg
    .replace(/^[\s\S]*?<svg[^>]*>/, '')
    .replace(/<\/svg>\s*$/, '')
    .replace(/\s+/g, ' ')
    .trim();
const entries = NAMES.map((n) => {
  const svg = readFileSync(
    new URL(`../node_modules/lucide-static/icons/${n}.svg`, import.meta.url),
    'utf8',
  );
  return `  '${n}': '${body(svg)}',`;
});
writeFileSync(
  new URL('../src/shared/icons.generated.ts', import.meta.url),
  `// Generated by scripts/make-icons.mjs from lucide-static (ISC license). Do not edit.\nexport const ICONS = {\n${entries.join('\n')}\n} as const;\n\nexport type IconName = keyof typeof ICONS;\n`,
);
