// Writes sw.js after the build: a cache-first service worker that precaches every emitted
// file, so the landing page and /app work offline after the first visit. It makes no network
// requests of its own: anything not in the cache gets a 404 instead of a network request.

import { createHash } from 'node:crypto';
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, resolve, sep } from 'node:path';
import type { Plugin, ResolvedConfig } from 'vite';

function walk(dir: string, out: string[] = []): string[] {
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) walk(full, out);
    else out.push(full);
  }
  return out;
}

export function precachePlugin(): Plugin {
  let config: ResolvedConfig;
  return {
    name: 'catchline-precache',
    apply: 'build',
    configResolved(c) {
      config = c;
    },
    closeBundle: {
      order: 'post',
      handler() {
        const outDir = resolve(config.root, config.build.outDir);
        if (!existsSync(outDir)) return;
        const files = walk(outDir)
          .map((f) => relative(outDir, f).split(sep).join('/'))
          .filter((f) => f !== 'sw.js' && !f.endsWith('.map') && !f.startsWith('stats/'))
          .sort();
        const hash = createHash('sha256');
        for (const f of files) {
          hash.update(f);
          hash.update(readFileSync(join(outDir, f)));
        }
        const version = hash.digest('hex').slice(0, 12);
        // Directory URLs (./ and ./app/) resolve to their index.html.
        const urls = ['./', ...files];
        const sw = `// Generated by plugins/precache.ts. Do not edit.
const VERSION = ${JSON.stringify(version)};
const CACHE = 'catchline-' + VERSION;
const PRECACHE = ${JSON.stringify(urls)};

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches
      .open(CACHE)
      .then((cache) => cache.addAll(PRECACHE.map((u) => new URL(u, self.location.href).href)))
      .then(() => self.skipWaiting()),
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) =>
        Promise.all(keys.filter((k) => k.startsWith('catchline-') && k !== CACHE).map((k) => caches.delete(k))),
      )
      .then(() => self.clients.claim()),
  );
});

// Cache first. A path without a file extension (/app, /app/) maps to its index.html.
// Nothing is requested from the network: everything the pages need is precached; a miss is a 404.
self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET') return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;
  event.respondWith(
    caches.open(CACHE).then(async (cache) => {
      const direct = await cache.match(request, { ignoreSearch: true, ignoreVary: true });
      if (direct) return direct;
      if (request.mode === 'navigate') {
        const dir = url.pathname.endsWith('/') ? url.pathname : url.pathname + '/';
        const page = await cache.match(new URL(dir + 'index.html', url.origin).href, { ignoreVary: true });
        if (page) return page;
      }
      return new Response('Not available offline.', { status: 404, headers: { 'content-type': 'text/plain' } });
    }),
  );
});
`;
        writeFileSync(join(outDir, 'sw.js'), sw);
      },
    },
  };
}
